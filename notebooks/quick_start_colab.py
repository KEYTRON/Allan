def quick_train_tokenizer(vocab_size=5000):
    """Быстрое обучение токенизатора на встроенных данных."""
    import os
    import sentencepiece as spm

    # Создаем временный файл
    temp_file = "/content/quick_train_data.txt"
    with open(temp_file, 'w', encoding='utf-8') as f:
        for text in ALL_TEXTS:
            f.write(text + '\n')

    size_mb = os.path.getsize(temp_file) / 1024 / 1024
    print(f"Размер файла: {size_mb:.2f} MB")

    # Обучаем
    print(f"Обучение токенизатора (vocab_size={vocab_size})...")
    spm.SentencePieceTrainer.train(
        input=temp_file,
        model_prefix="/content/allan_tokenizer",
        vocab_size=vocab_size,
        character_coverage=0.9995,
        model_type='bpe',
        pad_id=0,
        unk_id=1,
        bos_id=2,
        eos_id=3,
        pad_piece='<PAD>',
        unk_piece='<UNK>',
        bos_piece='<BOS>',
        eos_piece='<EOS>',
        num_threads=os.cpu_count(),
    )

    print("✓ Токенизатор обучен!")

    # Тестируем
    sp = spm.SentencePieceProcessor()
    sp.load("/content/allan_tokenizer.model")

    test_text = "Россия - это страна."
    tokens = sp.encode(test_text)
    decoded = sp.decode(tokens)

    print(f"\nТест: '{test_text}'")
    print(f"Токены: {tokens}")
    print(f"Декодировано: '{decoded}'")

    return "/content/allan_tokenizer.model"


def prepare_quick_dataset(tokenizer, max_length=128):
    """Подготовка быстрого датасета для обучения."""
    import torch

    print("Подготовка обучающих данных...")

    all_tokens = []
    for text in ALL_TEXTS:
        tokens = tokenizer.encode(text, add_bos=True, add_eos=True)

        # Паддинг или обрезка до max_length
        if len(tokens) < max_length:
            tokens = tokens + [tokenizer.pad_token_id] * (max_length - len(tokens))
        else:
            tokens = tokens[:max_length]

        all_tokens.append(tokens)

    # Конвертируем в тензор
    data_tensor = torch.tensor(all_tokens, dtype=torch.long)

    print(f"✓ Подготовлено примеров: {len(all_tokens)}")
    print(f"✓ Размер датасета: {data_tensor.shape}")

    return data_tensor


